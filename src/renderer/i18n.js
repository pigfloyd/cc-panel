  function normalizeLanguage(language) {
    return SUPPORTED_LANGUAGES.has(language) ? language : DEFAULT_LANGUAGE;
  }

  function translate(language, key, values = {}) {
    const normalized = normalizeLanguage(language);
    const template = messages[normalized][key] ?? messages[DEFAULT_LANGUAGE][key] ?? key;
    return template.replace(/\{(\w+)\}/g, (_match, name) => String(values[name] ?? ""));
  }

  function applyDocument(document, language) {
    const normalized = normalizeLanguage(language);
    document.documentElement.lang = normalized;
    for (const element of document.querySelectorAll("[data-i18n]")) {
      element.textContent = translate(normalized, element.dataset.i18n);
    }
    for (const element of document.querySelectorAll("[data-i18n-title]")) {
      element.title = translate(normalized, element.dataset.i18nTitle);
    }
    for (const element of document.querySelectorAll("[data-i18n-aria-label]")) {
      element.setAttribute("aria-label", translate(normalized, element.dataset.i18nAriaLabel));
    }
  }

  const api = { DEFAULT_LANGUAGE, normalizeLanguage, translate, applyDocument };
  root.appI18n = api;
  if (typeof module !== "undefined" && module.exports) module.exports = api;
